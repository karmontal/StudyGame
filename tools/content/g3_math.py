from common import mcq, tf, match, order, write_book


def _choices(ans, wrongs):
    out = [str(ans)]
    for w in wrongs:
        if isinstance(w, int) and w < 0:
            continue
        s = str(w)
        if s not in out:
            out.append(s)
        if len(out) == 4:
            break
    return out


def nocarry_add(a, b):
    """Adds column by column but forgets to carry (a common mistake)."""
    r, p = 0, 1
    while a or b:
        r += ((a % 10 + b % 10) % 10) * p
        a //= 10; b //= 10; p *= 10
    return r


def naive_sub(a, b):
    """Subtracts the smaller digit from the bigger one in each column (a common mistake)."""
    r, p = 0, 1
    while a or b:
        r += abs(a % 10 - b % 10) * p
        a //= 10; b //= 10; p *= 10
    return r


def add(a, b, q=None, explain=""):
    ans = a + b
    q = q or f"ما ناتج جمع {a} + {b}؟"
    return mcq(q, _choices(ans, [nocarry_add(a, b), ans + 10, ans - 100, ans + 1000, ans - 1, ans + 100]), explain=explain)


def sub(a, b, q=None, explain=""):
    ans = a - b
    q = q or f"ما ناتج طرح {b} من {a}؟"
    return mcq(q, _choices(ans, [naive_sub(a, b), ans + 10, ans - 100, ans + 100, a + b, ans + 1000]), explain=explain)


def mul(a, b, q=None, explain=""):
    ans = a * b
    q = q or f"ما ناتج {a} × {b}؟"
    return mcq(q, _choices(ans, [ans + b, ans - b, a + b, ans + a, ans - a, ans + 1]), explain=explain)


def div(a, b, q=None, explain=""):
    ans = a // b
    assert a % b == 0
    q = q or f"ما ناتج قسمة {a} على {b}؟"
    return mcq(q, _choices(ans, [ans + 1, ans - 1, a - b, ans + 2, b]), explain=explain)


def num(q, ans, wrongs, explain=""):
    return mcq(q, _choices(ans, wrongs), explain=explain)


def L(id, title, pages, questions):
    return {"id": id, "title": title, "pages": [pages[0] + 2, pages[1] + 2], "questions": questions}


def table_order(n):
    return order(f"رتّب نواتج الضرب في {n} من الأصغر إلى الأكبر", [str(n * k) for k in (2, 4, 6, 8)])


