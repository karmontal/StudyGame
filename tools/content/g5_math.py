def f(x):
    """Format a Fraction: integer, a/b, or mixed 'w و a/b'."""
    x = Fr(x)
    if x.denominator == 1:
        return str(x.numerator)
    w, r = divmod(x.numerator, x.denominator)
    return f"{w} و {r}/{x.denominator}" if w else f"{r}/{x.denominator}"


def mx(w, n, d):
    """Mixed number w n/d as a Fraction."""
    return Fr(w) + Fr(n, d)


def d(x):
    """Format a Decimal without trailing zeros."""
    s = format(D(x).normalize(), "f")
    return s


def num(q, right, wrong, explain=""):
    """mcq whose first choice is the computed answer; distractors must differ from it."""
    choices = [right] + [w for w in wrong if w != right]
    assert len(choices) == len(set(choices)), (q, choices)
    return mcq(q, choices[:4], explain=explain)


def factors(n):
    return [i for i in range(1, n + 1) if n % i == 0]


def pf(n):
    out, p = [], 2
    while n > 1:
        while n % p == 0:
            out.append(p)
            n //= p
        p += 1
    return out


def x_(*a):
    return " × ".join(map(str, a))


def lst(a):
    return "، ".join(map(str, a))


